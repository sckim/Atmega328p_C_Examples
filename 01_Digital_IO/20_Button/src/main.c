/*=======================================================*/
// Button : 내부 풀업으로 버튼을 읽어 LED 를 켠다 — DDRx · PORTx · PINx 세 레지스터
//
// 교재 15장 실습 15-2.  원천: 13주차A §8
// 검증 : PIO 6.2.0 / avr-gcc 7.3.0
//        버튼을 떼면 PINB 의 PB0 이 1, 누르면 0
//
// 이 예제의 요점은 세 레지스터가 **같은 핀의 서로 다른 면**이라는 것이다.
//   DDRB  : 방향   0 = 입력(리셋값), 1 = 출력
//   PORTB : 출력일 때는 출력값, **입력일 때는 내부 풀업 스위치**
//   PINB  : 지금 핀에 실제로 걸린 전압을 읽는다 (읽기 전용)
//
// 네 가지 조합
//   DDR=0, PORT=0 : 입력, 풀업 없음 — 플로팅. 값이 정해지지 않는다
//   DDR=0, PORT=1 : 입력 + 내부 풀업  <- 아두이노의 INPUT_PULLUP 이 이것이다
//   DDR=1, PORT=0 : 출력 Low
//   DDR=1, PORT=1 : 출력 High
//
// 연결 : 버튼  PB0(아두이노 8번) - 버튼 - GND
//        풀업이 칩 안에 있으므로 외부 저항이 필요 없다
//        LED   PB5(아두이노 13번) 온보드 LED
//        버튼을 누르면 핀이 GND 에 닿아 0 이 된다. 눌렀을 때 0 이 정상이다.
//
// bit_is_clear 는 비트를 **검사**하는 매크로이지 바꾸는 매크로가 아니다.
// 비트를 바꿀 때는 |= _BV(n) 과 &= ~_BV(n) 을 쓴다.
//
// 선행 학습 : 10_Blink        다음 단계 : 30_LED_bar
/*=======================================================*/
#ifndef F_CPU
#define F_CPU 16000000UL
#endif
#include <avr/io.h>
#include <util/delay.h>

#define BTN PB0                             // 아두이노 8번
#define LED PB5                             // 아두이노 13번, 온보드

int main(void)
{
    DDRB |=  (1 << LED);                    // LED 핀만 출력
    DDRB &= ~(1 << BTN);                    // 버튼 핀은 입력 (리셋값이다)
    PORTB |= (1 << BTN);                    // 입력 핀의 PORT 에 1 -> 내부 풀업 ON

    while (1) {
        // 눌리면 PINB 의 BTN 비트가 0 이 된다.
        // bit_is_clear 는 "그 비트가 0인가"를 묻는다. 값을 바꾸지 않는다.
        if (bit_is_clear(PINB, BTN)) {
            PORTB |= (1 << LED);            // 눌린 동안 켠다
        } else {
            PORTB &= ~(1 << LED);
        }

        _delay_ms(10);                      // 접점 떨림을 넘긴다 (디바운스)
    }
}
