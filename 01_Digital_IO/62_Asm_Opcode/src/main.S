;=======================================================
; Asm_Opcode : 명령 두 개짜리 프로그램. 기계어를 손으로 만들어 대조한다.
;
; 교재 8장 실습 8-1·8-2. 이 프로그램은 아무 쓸모가 없다. 쓸모는 크기에 있다.
; 명령이 둘뿐이라 기계어 전체를 손으로 계산해 볼 수 있고,
; .hex 파일도 두 줄이라 통째로 읽을 수 있다.
;
; 손으로 계산해 볼 것
;
;   inc Rd   의 opcode 는  1001 010d dddd 0011   (d 는 레지스터 번호 5비트)
;     r16 이면 d = 10000 이므로
;       1001 0101 0000 0011  =  0x9503
;     프로그램 메모리는 번지당 2바이트이고 리틀 엔디언으로 저장되므로
;     메모리에는 03 95 로 보인다.
;
;   rjmp k   의 opcode 는  1100 kkkk kkkk kkkk   (동작은 PC <- PC + k + 1)
;     한 줄 위로 가려면 k = -2 다. 목적지까지의 거리보다 절댓값이 하나 크다.
;     -2 의 12비트 2의 보수는 1111 1111 1110 = 0xFFE 이므로
;       1100 1111 1111 1110  =  0xCFFE
;     메모리에는 FE CF 로 보인다.
;
; 빌드한 뒤 확인한다.
;   avr-objdump -d .pio/build/uno/firmware.elf
;
; 빌드하면 136바이트가 나온다. 명령 둘은 4바이트인데 나머지 132바이트는
; 벡터 테이블(26 x 4 = 104바이트)과 시작 코드다. 내 코드는 0x80 번지부터 온다.
; 크기 차이는 언어 때문이 아니라 런타임 때문이라는 것을 여기서 볼 수 있다.
;
; 선행 학습 : 60_Asm_Blink
;=======================================================
.section .text
.global main

main:
Loop:
    inc  r16          ; r16 <- r16 + 1     0x9503  ->  메모리에 03 95
    rjmp Loop         ; PC <- PC + k + 1   0xCFFE  ->  메모리에 FE CF
